#include <stdio.h>

int main() {
    int n = 5;  // تعداد سطرها برای نیمه بالایی
    int i, j;

    // نیمه بالایی لوزی (شامل خط وسط)
    for (i = 1; i <= n; i++) {
        // چاپ فاصله‌های قبل از ستاره‌ها
        for (j = 1; j <= n - i; j++) {
            printf(" ");
        }

        // چاپ ستاره‌ها
        for (j = 1; j <= 2 * i - 1; j++) {
            printf("*");
        }

        printf("\n");
    }

    // نیمه پایینی لوزی
    for (i = n - 1; i >= 1; i--) {
        // چاپ فاصله‌های قبل از ستاره‌ها
        for (j = 1; j <= n - i; j++) {
            printf(" ");
        }

        // چاپ ستاره‌ها
        for (j = 1; j <= 2 * i - 1; j++) {
            printf("*");
        }

        printf("\n");
    }

    return 0;
}
